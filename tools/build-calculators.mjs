async function main() {
  const dir = join(ROOT, 'calculators');
  for (const calc of calculators) await checkRepoLinks(calc.slug, JSON.stringify(calc));
  const pages = [
    ...calculators.map(calc => [join(dir, calc.slug, 'index.html'), calculatorPage(calc)]),
    [join(dir, 'index.html'), hubPage()],
  ].map(([file, html]) => [file, html.replace(/[ \t]+\n/g, '\n')]);
  if (process.argv.includes('--check')) {
    const stale = [];
    for (const [file, html] of pages) {
      const current = await readFile(file, 'utf-8').catch(() => null);
      if (current !== html) stale.push(file.slice(ROOT.length + 1));
    }
    if (stale.length) {
      console.error(`Out of date (run node tools/build-calculators.mjs): ${stale.join(', ')}`);
      process.exitCode = 1;
    }
    return;
  }
  for (const [file, html] of pages) {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, html, 'utf-8');
  }
  console.log(`Built ${calculators.length} calculator page(s) + index.`);
}

main().catch(err => { console.error(err); process.exitCode = 1; });
