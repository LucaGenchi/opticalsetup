// one calculators/<slug>/index.html per calculator. Formulas are pre-rendered
// by KaTeX, as in the wiki, so no KaTeX script ships. The interactive part of
// each page is its own module (calculators/<slug>/<script>), which renders
// the inputs from the calculator's schema and calls the app's functions.
// The output is committed; run this after changing the content or the
// shared page template, then check the diff.

